"""Prompts for LLM-based intent dataset generation.

设计目标：避免简单模板复制或同义词替换，生成贴近运维人员真实表达、
且包含困难样本（hard negative / 多意图边界 / 模糊指代）的训练数据。
"""

INTENT_DEFINITIONS = {
    "fault_diagnosis": (
        "故障诊断：描述故障现象并请求定位/排查。通常含设备、告警、数值或时间线索，"
        "如“ONU频繁闪断，收光-29，昨天还报LOS，怎么排查”。"
    ),
    "knowledge_qa": (
        "知识问答：询问光网络领域的事实/参数/规范/原理，不要求处理具体故障，"
        "如“ONU 正常的接收光功率范围是多少”。"
    ),
    "operation_guide": (
        "操作指导：请求某项操作的方法/步骤/流程，如“怎么清洁光纤连接器”、"
        "“更换光模块前要做哪些准备”。"
    ),
    "alarm_explanation": (
        "告警解释：询问某告警码的含义、产生原因或与其他告警的区别，"
        "如“LOS 是什么意思”、“LOF 和 LOS 有什么区别”。"
    ),
    "history_query": (
        "历史查询：请求回顾本会话或历史会话中问过/答过的内容，"
        "如“我刚才问的那个告警是什么来着”。"
    ),
    "small_talk": (
        "闲聊：问候、感谢、告别、身份询问等非业务对话，"
        "如“在吗”、“辛苦了”。可以含少量业务词但目的不是获取知识。"
    ),
    "unsupported": (
        "域外请求：与光网络运维无关的请求，如天气、股票、写诗、闲聊式纯聊天机器人的"
        "泛化请求。注意：域外但用运维口吻表达的也算此类（hard negative 方向）。"
    ),
    "ambiguous": (
        "意图模糊：信息量过低或多种意图混杂、无法判断真实目的的提问，"
        "如“这个怎么办”、“不行了”、“帮我看下”、只有设备名没有请求动作。"
        "标注 ambiguous 而不是猜测一个具体意图。"
    ),
}

DIVERSITY_REQUIREMENTS = """生成时必须覆盖以下多样性维度（禁止逐条套同一句式）：
1. 表达方式多样性：疑问/陈述/祈使/口语倒装/带语气词（呗、哈、急等）。
2. 口语化：一线运维的真实口吻，例如“师傅们这啥情况”“帮我瞅瞅”“现场急等”。
3. 错别字：注入真实常见的同音/近形错别字，如“光衰”写成“光衰/光捎”、“接收”→“接搜”、
   “掉线”→“调线”、“功率”→“公率”、“告警”→“告井/靠警”（每条至多 1-2 处，保持可读）。
4. 简写/缩略：“接收光功率”→“收光”、“光猫”代 ONU、“PON 口”→“P口”、省略单位 dBm。
5. 不完整 Query：缺少主语或宾语的片段，如“一直闪红灯”、“-27 还能用吗”。
6. 多意图边界样本：一句话里混两个意图，以主意图为准标注（如“LOS是啥意思，顺便说下咋处理”
   主意图是 alarm_explanation）。
7. Hard Negative：与某意图形似但标签不同的样本，如“查一下今天的天气”与
   “查一下今天的告警工单”（前者 unsupported，后者 history_query 语义）。
8. 同词不同意图：同一个关键词出现在不同意图中，如“光功率”分别出现在
   knowledge_qa（正常范围）、fault_diagnosis（光功率异常掉线）、operation_guide（怎么测光功率）。
9. 模糊指代：使用“它/这个/那个/刚才说的”等指代词，需要上下文才能理解。
10. 真实风格：夹杂工单/网管/值班语境，如“割接后”、“昨晚值班”、“网管上刷屏”。
"""

SYSTEM_PROMPT = (
    "你是光网络运维系统的训练数据生成引擎。你的任务是按照给定意图定义和多样性要求，"
    "批量生成一线运维人员的真实提问。\n"
    "严格要求：\n"
    "- 每条样本必须是自然、互不相同的句子；禁止模板复制；禁止只做同义词替换。\n"
    "- 同一批内的句式、长度、语气、信息完整度都要变化。\n"
    "- 设备词表：ONU/ONT/OLT/PON口/光模块/光纤/ODF/传输设备；"
    "告警词表：LOS/LOF/OOF/CRC_ERROR/BER_HIGH/DYING_GASP/AUTH_FAIL/RX_POWER_LOW。\n"
    "- 数值要物理合理（接收光功率典型 -8 ~ -30 dBm，超过 -27/-28 视为弱光边缘）。\n"
    "- 不生成任何与政治、暴力、色情相关的内容。\n\n"
    + DIVERSITY_REQUIREMENTS
    + '\n只输出 JSON 数组，每个元素形如 {"text": "提问原文", "intent": "意图标签"}，'
    "不要输出解释文字。"
)


def build_user_prompt(intent: str, count: int, avoid_examples: list[str]) -> str:
    definition = INTENT_DEFINITIONS.get(intent, "未知意图")
    avoid_text = (
        "\n".join(f"- {example}" for example in avoid_examples[-12:])
        if avoid_examples
        else "（首批，无 avoidance 约束）"
    )
    return (
        f"目标意图：{intent}\n定义：{definition}\n\n"
        f"请生成 {count} 条该意图的提问样本。\n\n"
        f"避免与以下已生成样本重复或过于相似（句式也不得雷同）：\n{avoid_text}\n\n"
        "只输出 JSON 数组。"
    )
